test('여러 스타일 알림장 채점', () => {
  const s = score(STYLES);
  const pct = (v) => `${(v * 100).toFixed(1)}%`;
  console.log(`\n[스타일 채점] 글 ${s.cases}개 · 맞게 뽑은 비율 ${pct(s.precision)} · 빠짐없이 뽑은 비율 ${pct(s.recall)} · 날짜 ${pct(s.date)}`);
  for (const f of s.fails) {
    console.log(`  ${f.key}${f.wrong.length ? ` | 잘못 뽑음: ${f.wrong.join(' / ')}` : ''}${f.missed.length ? ` | 놓침: ${f.missed.join(' / ')}` : ''}${f.date ? ` | 날짜 ${f.date}` : ''}`);
  }
  assert.ok(s.cases === STYLES.length);
});
